// Writes public/_headers (Cloudflare Pages) from security-headers.conf, the headers nginx
// sends in the Docker image, so both serve the same headers. The CSP's connect-src gets
// the origin of VITE_API_URL, read the way Vite reads it for the bundle (process env,
// then .env files); without one it falls back to the local backend.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadEnv } from 'vite';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const apiUrl = loadEnv('production', root, 'VITE_').VITE_API_URL || 'http://localhost:8000';
const apiOrigin = new URL(apiUrl).origin;

const conf = readFileSync(join(root, 'security-headers.conf'), 'utf8');
const headers = [...conf.matchAll(/^add_header\s+(\S+)\s+"([^"]*)"/gm)].map(
  ([, name, value]) => `  ${name}: ${value.replace('__API_ORIGIN__', apiOrigin)}`
);
if (headers.length === 0) {
  throw new Error('No add_header lines found in security-headers.conf');
}

const out = [
  '# Generated by scripts/gen-headers.mjs from security-headers.conf; do not edit.',
  '/*',
  ...headers,
  '',
  // Vite puts content-hashed files here, like nginx's 1y cache for static assets.
  '/assets/*',
  '  Cache-Control: public, max-age=31536000, immutable',
  '',
].join('\n');

writeFileSync(join(root, 'public', '_headers'), out);
console.log(`public/_headers written, connect-src 'self' ${apiOrigin}`);
